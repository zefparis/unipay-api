-- ============================================================
-- Migration: partner (referral) program
-- Version   : 20261027000000
-- Run via   : supabase db push
--             OR paste directly into Supabase SQL Editor
-- ============================================================
--
-- A partner merchant brings its own sub-merchants via a referral
-- link (?ref=<partner_code>). The partner earns a configurable
-- commission (default 1%) on each SUCCESSFUL fee-bearing
-- transaction of its sub-merchants.
--
--   commission = LEAST(partner_rate * amount, fee - amount * provider_fee_rate)
--
-- The commission is taken OUT OF UniPay's margin, never added on
-- top of the client fee. It is credited to the partner's merchant
-- settlement ledger (same balance used by /merchant/settlement/request)
-- inside the SAME SQL transaction as the commission row.
--
-- Idempotency: UNIQUE(transaction_id) on partner_commissions —
-- the Unipesa callback and the reconciliation worker can both
-- trigger the computation without ever creating a duplicate.
-- Reversals are counter-entries (status='reversed'), never deletes.

-- ── 1. merchants: partner columns ────────────────────────────
ALTER TABLE public.merchants
  ADD COLUMN IF NOT EXISTS is_partner boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS partner_code text,
  ADD COLUMN IF NOT EXISTS partner_rate numeric(6,4) NOT NULL DEFAULT 0.01,
  ADD COLUMN IF NOT EXISTS referred_by_partner_id uuid
    REFERENCES public.merchants(id) ON DELETE SET NULL;

-- partner_code is generated by the admin route only (UNIQUE, nullable).
CREATE UNIQUE INDEX IF NOT EXISTS idx_merchants_partner_code
  ON public.merchants (partner_code)
  WHERE partner_code IS NOT NULL;

ALTER TABLE public.merchants
  DROP CONSTRAINT IF EXISTS merchants_partner_rate_check;
ALTER TABLE public.merchants
  ADD CONSTRAINT merchants_partner_rate_check
  CHECK (partner_rate >= 0 AND partner_rate <= 1);

-- Self-referral is impossible at the DB level.
ALTER TABLE public.merchants
  DROP CONSTRAINT IF EXISTS merchants_no_self_referral;
ALTER TABLE public.merchants
  ADD CONSTRAINT merchants_no_self_referral
  CHECK (referred_by_partner_id IS NULL OR referred_by_partner_id <> id);

CREATE INDEX IF NOT EXISTS idx_merchants_referred_by
  ON public.merchants (referred_by_partner_id)
  WHERE referred_by_partner_id IS NOT NULL;

-- ── 2. partner_commissions ───────────────────────────────────
CREATE TABLE IF NOT EXISTS public.partner_commissions (
  id                     uuid          PRIMARY KEY DEFAULT gen_random_uuid(),
  partner_merchant_id    uuid          NOT NULL REFERENCES public.merchants(id) ON DELETE RESTRICT,
  sub_merchant_id        uuid          NOT NULL REFERENCES public.merchants(id) ON DELETE RESTRICT,
  transaction_id         uuid          NOT NULL REFERENCES public.transactions(id) ON DELETE RESTRICT,
  currency               text          NOT NULL
                                         CHECK (currency IN ('CDF', 'USD', 'USDT')),
  transaction_amount     numeric(20,4) NOT NULL CHECK (transaction_amount > 0),
  rate                   numeric(6,4)  NOT NULL,
  commission_amount      numeric(20,4) NOT NULL CHECK (commission_amount > 0),
  status                 text          NOT NULL DEFAULT 'credited'
                                         CHECK (status IN ('credited', 'reversed')),
  ledger_entry_id        uuid          REFERENCES public.merchant_ledger_entries(id) ON DELETE SET NULL,
  reversal_ledger_entry_id uuid        REFERENCES public.merchant_ledger_entries(id) ON DELETE SET NULL,
  created_at             timestamptz   NOT NULL DEFAULT now(),
  reversed_at            timestamptz,
  reverse_reason         text,
  -- Strict idempotency: exactly ONE commission row per transaction.
  CONSTRAINT partner_commissions_transaction_unique UNIQUE (transaction_id)
);

CREATE INDEX IF NOT EXISTS idx_partner_commissions_partner
  ON public.partner_commissions (partner_merchant_id, created_at);

CREATE INDEX IF NOT EXISTS idx_partner_commissions_sub
  ON public.partner_commissions (sub_merchant_id, created_at);

CREATE INDEX IF NOT EXISTS idx_partner_commissions_status
  ON public.partner_commissions (status);

ALTER TABLE public.partner_commissions ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "partner_commissions_service_role_all" ON public.partner_commissions;
CREATE POLICY "partner_commissions_service_role_all"
  ON public.partner_commissions FOR ALL TO service_role
  USING (true) WITH CHECK (true);

-- ── 3. credit_partner_commission ─────────────────────────────
-- Single commission-crediting primitive, used by:
--   * process_wallet_provider_callback (inbound callback AND
--     reconciliation worker share that path), and
--   * backfill_partner_commissions (admin backfill route).
--
-- Returns a JSONB status object:
--   {status:'credited', commission_id, partner_merchant_id, sub_merchant_id,
--    amount, currency, rate, transaction_id, ledger_entry_id}
--   {status:'skipped_duplicate'}               — commission already exists
--   {status:'no_margin', ...}                  — margin cap <= 0
--   {status:'none', reason}                    — not eligible
--
-- Eligibility:
--   * transactions.status = 'success'
--   * merchant-side tx (merchant_id NOT NULL, wallet_user_id IS NULL)
--   * fee-bearing tx (fee > 0) — excludes settlement payouts
--     (fee = 0, metadata.source = 'merchant_settlement') and any
--     internal/zero-fee row. Settlement-linked rows are excluded
--     explicitly as well.
--   * the merchant is referred (referred_by_partner_id NOT NULL)
--   * the partner is active and still flagged is_partner
CREATE OR REPLACE FUNCTION public.credit_partner_commission(
  p_transaction_id UUID,
  p_provider_fee_rate NUMERIC DEFAULT NULL
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_tx public.transactions%ROWTYPE;
  v_sub public.merchants%ROWTYPE;
  v_partner public.merchants%ROWTYPE;
  v_commission NUMERIC;
  v_commission_id UUID;
  v_balance NUMERIC := 0;
  v_ledger_id UUID;
BEGIN
  -- Fail loud: a missing provider fee rate means the margin cap cannot
  -- be computed — never silently overpay a commission.
  IF p_provider_fee_rate IS NULL THEN
    RETURN jsonb_build_object('status', 'error', 'message', 'provider_fee_rate missing');
  END IF;

  SELECT * INTO v_tx
  FROM public.transactions
  WHERE id = p_transaction_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('status', 'none', 'reason', 'transaction_not_found');
  END IF;

  IF v_tx.status <> 'success'
     OR v_tx.merchant_id IS NULL
     OR v_tx.wallet_user_id IS NOT NULL
     OR v_tx.settlement_request_id IS NOT NULL
     OR v_tx.fee IS NULL OR v_tx.fee <= 0 THEN
    RETURN jsonb_build_object('status', 'none', 'reason', 'not_eligible');
  END IF;

  SELECT * INTO v_sub
  FROM public.merchants
  WHERE id = v_tx.merchant_id;

  IF v_sub.referred_by_partner_id IS NULL
     OR v_sub.referred_by_partner_id = v_tx.merchant_id THEN
    RETURN jsonb_build_object('status', 'none', 'reason', 'no_referrer');
  END IF;

  SELECT * INTO v_partner
  FROM public.merchants
  WHERE id = v_sub.referred_by_partner_id;

  IF NOT FOUND
     OR v_partner.is_partner IS NOT TRUE
     OR v_partner.status <> 'active' THEN
    RETURN jsonb_build_object('status', 'none', 'reason', 'partner_inactive');
  END IF;

  -- Commission base = gross amount, capped by the real UniPay margin
  -- on this transaction (fee charged minus provider cost).
  v_commission := ROUND(
    LEAST(
      v_partner.partner_rate * v_tx.amount,
      v_tx.fee - v_tx.amount * p_provider_fee_rate
    ),
    4
  );

  IF v_commission IS NULL OR v_commission <= 0 THEN
    RETURN jsonb_build_object(
      'status', 'no_margin',
      'transaction_id', v_tx.id,
      'fee', v_tx.fee,
      'amount', v_tx.amount
    );
  END IF;

  -- Idempotency: UNIQUE(transaction_id). A concurrent caller
  -- (callback + reconciliation, or backfill) hits the conflict and
  -- gets skipped_duplicate — never a second ledger credit.
  INSERT INTO public.partner_commissions (
    partner_merchant_id, sub_merchant_id, transaction_id,
    currency, transaction_amount, rate, commission_amount
  ) VALUES (
    v_partner.id, v_sub.id, v_tx.id,
    upper(v_tx.currency), v_tx.amount, v_partner.partner_rate, v_commission
  )
  ON CONFLICT (transaction_id) DO NOTHING
  RETURNING id INTO v_commission_id;

  IF v_commission_id IS NULL THEN
    RETURN jsonb_build_object('status', 'skipped_duplicate', 'transaction_id', v_tx.id);
  END IF;

  -- Credit the partner's settlement ledger in the SAME transaction.
  -- type='credit' keeps every existing balance aggregation
  -- (SUM(CASE WHEN type='credit' THEN amount ELSE -amount END)) correct.
  SELECT COALESCE(SUM(
    CASE WHEN type = 'credit' THEN amount ELSE -amount END
  ), 0)
  INTO v_balance
  FROM public.merchant_ledger_entries
  WHERE merchant_id = v_partner.id
    AND currency = upper(v_tx.currency);

  v_balance := v_balance + v_commission;

  INSERT INTO public.merchant_ledger_entries (
    merchant_id, transaction_id, type, amount, balance_after, currency
  ) VALUES (
    v_partner.id, v_tx.id, 'credit', v_commission,
    v_balance, upper(v_tx.currency)
  )
  RETURNING id INTO v_ledger_id;

  UPDATE public.partner_commissions
  SET ledger_entry_id = v_ledger_id
  WHERE id = v_commission_id;

  RETURN jsonb_build_object(
    'status', 'credited',
    'commission_id', v_commission_id,
    'partner_merchant_id', v_partner.id,
    'sub_merchant_id', v_sub.id,
    'transaction_id', v_tx.id,
    'amount', v_commission,
    'currency', upper(v_tx.currency),
    'rate', v_partner.partner_rate,
    'ledger_entry_id', v_ledger_id
  );
END;
$$;

-- ── 4. reverse_partner_commission ────────────────────────────
-- Counter-entry (contrepassation) for a previously credited
-- commission — e.g. the underlying transaction was later refunded
-- or cancelled. The commission row is marked 'reversed' and a
-- NEGATIVE 'credit' ledger entry is written for the partner, so
-- every balance aggregation subtracts it. The row is never deleted.
-- Idempotent: reversing an already-reversed commission returns
-- {status:'already_reversed'} without touching the ledger.
CREATE OR REPLACE FUNCTION public.reverse_partner_commission(
  p_transaction_id UUID,
  p_reason TEXT DEFAULT NULL
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_comm public.partner_commissions%ROWTYPE;
  v_balance NUMERIC := 0;
  v_ledger_id UUID;
BEGIN
  SELECT * INTO v_comm
  FROM public.partner_commissions
  WHERE transaction_id = p_transaction_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('status', 'none', 'reason', 'commission_not_found');
  END IF;

  IF v_comm.status = 'reversed' THEN
    RETURN jsonb_build_object('status', 'already_reversed', 'commission_id', v_comm.id);
  END IF;

  SELECT COALESCE(SUM(
    CASE WHEN type = 'credit' THEN amount ELSE -amount END
  ), 0)
  INTO v_balance
  FROM public.merchant_ledger_entries
  WHERE merchant_id = v_comm.partner_merchant_id
    AND currency = v_comm.currency;

  -- Negative 'credit': ledger entries have no CHECK on amount, and
  -- every balance computation treats this as a subtraction.
  v_balance := v_balance - v_comm.commission_amount;

  INSERT INTO public.merchant_ledger_entries (
    merchant_id, transaction_id, type, amount, balance_after, currency
  ) VALUES (
    v_comm.partner_merchant_id, v_comm.transaction_id, 'credit',
    -v_comm.commission_amount, v_balance, v_comm.currency
  )
  RETURNING id INTO v_ledger_id;

  UPDATE public.partner_commissions
  SET status = 'reversed',
      reversed_at = now(),
      reverse_reason = p_reason,
      reversal_ledger_entry_id = v_ledger_id
  WHERE id = v_comm.id;

  RETURN jsonb_build_object(
    'status', 'reversed',
    'commission_id', v_comm.id,
    'partner_merchant_id', v_comm.partner_merchant_id,
    'amount', v_comm.commission_amount,
    'currency', v_comm.currency,
    'reversal_ledger_entry_id', v_ledger_id
  );
END;
$$;

-- ── 5. backfill_partner_commissions ──────────────────────────
-- Admin backfill: recomputes commissions for successful fee-bearing
-- transactions of referred merchants in a date range (created_at).
-- Idempotent via credit_partner_commission's ON CONFLICT guard.
-- A failure on one row is contained (plpgsql savepoint) and does
-- not abort the batch.
CREATE OR REPLACE FUNCTION public.backfill_partner_commissions(
  p_date_from TIMESTAMPTZ,
  p_date_to TIMESTAMPTZ,
  p_provider_fee_rate NUMERIC DEFAULT NULL
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_tx_id UUID;
  v_result JSONB;
  v_credited INTEGER := 0;
  v_skipped INTEGER := 0;
  v_no_margin INTEGER := 0;
  v_none INTEGER := 0;
  v_errors INTEGER := 0;
BEGIN
  -- Same rule as credit_partner_commission: NULL provider fee rate
  -- means the margin cap is unknown — refuse the whole batch.
  IF p_provider_fee_rate IS NULL THEN
    RETURN jsonb_build_object('status', 'error', 'message', 'provider_fee_rate missing');
  END IF;

  FOR v_tx_id IN
    SELECT t.id
    FROM public.transactions t
    JOIN public.merchants m ON m.id = t.merchant_id
    WHERE t.status = 'success'
      AND t.merchant_id IS NOT NULL
      AND t.wallet_user_id IS NULL
      AND t.settlement_request_id IS NULL
      AND t.fee > 0
      AND m.referred_by_partner_id IS NOT NULL
      AND t.created_at >= p_date_from
      AND t.created_at < p_date_to
    ORDER BY t.created_at
  LOOP
    BEGIN
      v_result := public.credit_partner_commission(v_tx_id, p_provider_fee_rate);
      CASE v_result->>'status'
        WHEN 'credited'          THEN v_credited := v_credited + 1;
        WHEN 'skipped_duplicate' THEN v_skipped := v_skipped + 1;
        WHEN 'no_margin'         THEN v_no_margin := v_no_margin + 1;
        ELSE                          v_none := v_none + 1;
      END CASE;
    EXCEPTION WHEN OTHERS THEN
      v_errors := v_errors + 1;
    END;
  END LOOP;

  RETURN jsonb_build_object(
    'credited', v_credited,
    'skipped_duplicate', v_skipped,
    'no_margin', v_no_margin,
    'not_eligible', v_none,
    'errors', v_errors
  );
END;
$$;

-- ── 6. process_wallet_provider_callback — + partner commission ─
-- Rebuilt EXACTLY from the deployed 20260929000000 version
-- (wallet_withdraw_fail_and_refund delegation included). Only diff:
--   a) new trailing param p_provider_fee_rate (DEFAULT NULL — passed
--      by every caller from env AVADA_FEE_RATE; a NULL rate returns a
--      commission 'error', it never silently commissions)
--   b) a commission block AFTER the transaction status UPDATE, in an
--      EXCEPTION-isolated sub-block: a commission error can NEVER
--      abort the status transition or the merchant ledger credit.
--   c) 'partner_commission' field in the returned JSONB.
DROP FUNCTION IF EXISTS public.process_wallet_provider_callback(TEXT, TEXT, UUID, TEXT, TEXT, JSONB);
CREATE OR REPLACE FUNCTION public.process_wallet_provider_callback(
  p_provider TEXT,
  p_provider_event_id TEXT,
  p_transaction_id UUID,
  p_new_status TEXT,
  p_provider_transaction_id TEXT,
  p_payload JSONB DEFAULT '{}'::jsonb,
  p_provider_fee_rate NUMERIC DEFAULT NULL
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_claimed UUID;
  v_tx public.transactions%ROWTYPE;
  v_credit NUMERIC := 0;
  v_refund NUMERIC := 0;
  v_merchant_balance NUMERIC := 0;
  v_merchant_recredit NUMERIC := 0;
  v_settlement_updated BOOLEAN := false;
  v_merged_metadata JSONB;
  v_partner_commission JSONB := jsonb_build_object('status', 'none');
BEGIN
  IF p_provider IS NULL OR p_provider_event_id IS NULL OR p_provider_event_id = '' THEN
    RAISE EXCEPTION 'INVALID_PROVIDER_EVENT';
  END IF;
  IF p_new_status NOT IN ('success', 'failed') THEN
    RAISE EXCEPTION 'INVALID_TRANSACTION_STATUS';
  END IF;

  INSERT INTO public.provider_webhook_events (
    provider, provider_event_id, transaction_id, payload
  ) VALUES (
    p_provider, p_provider_event_id, p_transaction_id, COALESCE(p_payload, '{}'::jsonb)
  )
  ON CONFLICT (provider, provider_event_id) DO NOTHING
  RETURNING id INTO v_claimed;

  IF v_claimed IS NULL THEN
    RETURN jsonb_build_object('processed', false, 'duplicate', true);
  END IF;

  SELECT * INTO v_tx
  FROM public.transactions
  WHERE id = p_transaction_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'TRANSACTION_NOT_FOUND';
  END IF;

  IF v_tx.status IN ('success', 'failed', 'cancelled') THEN
    RETURN jsonb_build_object('processed', false, 'already_terminal', true);
  END IF;

  -- ── Wallet user credits/refunds ──────────────────────────────
  IF p_new_status = 'success' AND v_tx.direction = 'collect' AND v_tx.wallet_user_id IS NOT NULL THEN
    v_credit := v_tx.net_amount;
    IF upper(v_tx.currency) = 'CDF' THEN
      UPDATE public.wallet_users
      SET balance_cdf = balance_cdf + v_credit, updated_at = now()
      WHERE id = v_tx.wallet_user_id;
    ELSIF upper(v_tx.currency) = 'USD' THEN
      UPDATE public.wallet_users
      SET usd_balance = usd_balance + v_credit, updated_at = now()
      WHERE id = v_tx.wallet_user_id;
    ELSIF upper(v_tx.currency) = 'USDT' THEN
      UPDATE public.wallet_users
      SET usdt_balance = usdt_balance + v_credit, updated_at = now()
      WHERE id = v_tx.wallet_user_id;
    ELSE
      RAISE EXCEPTION 'UNSUPPORTED_WALLET_CURRENCY: %', v_tx.currency;
    END IF;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'WALLET_NOT_FOUND';
    END IF;
  ELSIF p_new_status = 'failed' AND v_tx.direction = 'payout' AND v_tx.wallet_user_id IS NOT NULL THEN
    -- Single transition path: atomic refund + 'failed' under the tx
    -- and wallet locks. The tx row is already FOR UPDATE here —
    -- re-locking in the callee is a no-op within this transaction.
    SELECT (r->>'refunded')::numeric INTO v_refund
    FROM public.wallet_withdraw_fail_and_refund(
      v_tx.id,
      'provider_callback_failed'
    ) AS r;
  END IF;

  -- ── Merchant ledger credit on collect success ────────────────
  IF p_new_status = 'success' AND v_tx.direction = 'collect'
     AND v_tx.wallet_user_id IS NULL AND v_tx.merchant_id IS NOT NULL THEN

    SELECT COALESCE(SUM(
      CASE WHEN type = 'credit' THEN amount ELSE -amount END
    ), 0)
    INTO v_merchant_balance
    FROM public.merchant_ledger_entries
    WHERE merchant_id = v_tx.merchant_id
      AND currency = upper(v_tx.currency);

    v_merchant_balance := v_merchant_balance + v_tx.net_amount;

    INSERT INTO public.merchant_ledger_entries (
      merchant_id, transaction_id, type, amount, balance_after, currency
    ) VALUES (
      v_tx.merchant_id, v_tx.id, 'credit', v_tx.net_amount,
      v_merchant_balance, upper(v_tx.currency)
    );
  END IF;

  -- ── Merchant ledger re-credit on payout failure ──────────────
  -- Merchant payouts (wallet_user_id IS NULL) are re-credited here;
  -- wallet payouts are handled by wallet_withdraw_fail_and_refund.
  IF p_new_status = 'failed' AND v_tx.direction = 'payout'
     AND v_tx.wallet_user_id IS NULL AND v_tx.merchant_id IS NOT NULL THEN

    SELECT amount INTO v_merchant_recredit
    FROM public.merchant_ledger_entries
    WHERE transaction_id = v_tx.id
      AND type = 'payout'
    LIMIT 1;

    IF v_merchant_recredit IS NOT NULL AND v_merchant_recredit > 0 THEN
      SELECT COALESCE(SUM(
        CASE WHEN type = 'credit' THEN amount ELSE -amount END
      ), 0)
      INTO v_merchant_balance
      FROM public.merchant_ledger_entries
      WHERE merchant_id = v_tx.merchant_id
        AND currency = upper(v_tx.currency);

      v_merchant_balance := v_merchant_balance + v_merchant_recredit;

      INSERT INTO public.merchant_ledger_entries (
        merchant_id, transaction_id, type, amount, balance_after, currency
      ) VALUES (
        v_tx.merchant_id, v_tx.id, 'credit', v_merchant_recredit,
        v_merchant_balance, upper(v_tx.currency)
      );
    END IF;
  END IF;

  -- ── Update transaction status (merge metadata, don't overwrite)
  -- Read metadata fresh: on the wallet-payout-failed path the refund
  -- RPC has already appended refund_reason/refunded_amount, which we
  -- want preserved under merchant_metadata.
  SELECT metadata INTO v_merged_metadata
  FROM public.transactions WHERE id = v_tx.id;

  v_merged_metadata := jsonb_build_object(
    'merchant_metadata', v_merged_metadata,
    'provider_payload', COALESCE(p_payload, null)
  );

  UPDATE public.transactions
  SET status = p_new_status,
      avada_transaction_id = COALESCE(p_provider_transaction_id, avada_transaction_id),
      metadata = v_merged_metadata,
      updated_at = now()
  WHERE id = v_tx.id;

  -- ── Partner commission (isolated) ────────────────────────────
  -- Runs AFTER the status UPDATE so credit_partner_commission sees
  -- status='success'. Wrapped in a sub-block: any commission error
  -- rolls back only this block, never the status transition or the
  -- merchant ledger credit.
  IF p_new_status = 'success' THEN
    BEGIN
      v_partner_commission := public.credit_partner_commission(
        v_tx.id, p_provider_fee_rate
      );
    EXCEPTION WHEN OTHERS THEN
      v_partner_commission := jsonb_build_object(
        'status', 'error',
        'message', SQLERRM
      );
    END;
  END IF;

  -- ── Settlement propagation ───────────────────────────────────
  IF v_tx.settlement_request_id IS NOT NULL THEN
    IF p_new_status = 'success' THEN
      BEGIN
        PERFORM public.mark_settlement_success(
          v_tx.settlement_request_id,
          COALESCE(p_provider_transaction_id, v_tx.avada_transaction_id)
        );
        v_settlement_updated := true;
      EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE 'Settlement % mark_success skipped: %',
          v_tx.settlement_request_id, SQLERRM;
      END;
    ELSIF p_new_status = 'failed' THEN
      BEGIN
        PERFORM public.mark_settlement_failed(
          v_tx.settlement_request_id,
          'Provider callback: payout failed'
        );
        v_settlement_updated := true;
      EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE 'Settlement % mark_failed skipped: %',
          v_tx.settlement_request_id, SQLERRM;
      END;
    END IF;
  END IF;

  RETURN jsonb_build_object(
    'processed', true,
    'duplicate', false,
    'credited', v_credit,
    'refunded', v_refund,
    'status', p_new_status,
    'merchant_ledger_credited',
      (p_new_status = 'success' AND v_tx.direction = 'collect'
       AND v_tx.wallet_user_id IS NULL AND v_tx.merchant_id IS NOT NULL),
    'merchant_ledger_recredited',
      (p_new_status = 'failed' AND v_tx.direction = 'payout'
       AND v_tx.wallet_user_id IS NULL AND v_tx.merchant_id IS NOT NULL
       AND v_merchant_recredit > 0),
    'merchant_ledger_currency', upper(v_tx.currency),
    'settlement_updated', v_settlement_updated,
    'partner_commission', v_partner_commission
  );
END;
$$;

